import type { SeedItem, SeedType } from '../seed-types';

/**
 * Regions, and the districts and district-level cities under them (§6.3
 * "Region, district/city", §7.1 Location).
 *
 * Fourteen first-level units: twelve regions, the Republic of Karakalpakstan and
 * the city of Tashkent. Districts hang off them by `parentCode`, so the client's
 * location picker is region → district with no bespoke tree endpoint.
 *
 * **Two things the client must confirm against the official register**, because
 * they are administrative facts rather than engineering choices:
 *
 * 1. District-vs-city status. Several entries below share a name with the city at
 *    their centre (Samarqand, Buxoro, Nukus, Termiz), and in the official register
 *    the city is sometimes a separate district-level unit. Where that matters for
 *    hiring, the city needs its own row.
 * 2. Recent redistricting. Districts are created, renamed and merged by decree
 *    more often than any other dictionary here; Jizzakh's Sharof Rashidov district
 *    and Tashkent's Yangihayot are both recent examples.
 *
 * Neither is a blocker: a correction is an edit to this file plus `pnpm seed`, and
 * `merged_into_id` keeps any already-referenced id resolvable (§10.3).
 */

/**
 * One location row.
 *
 * Positional labels, in the order **uz-Latn, uz-Cyrl, ru, en**. Compact enough to
 * review a whole region at a glance, which matters for 175 rows - and a swapped
 * column is caught by the script assertions in `dictionaries.int.spec.ts` (a
 * Latin-script slot may never contain Cyrillic, and vice versa).
 */
function place(
  code: string,
  uzLatn: string,
  uzCyrl: string,
  ru: string,
  en: string,
  parentCode?: string,
): SeedItem {
  return {
    code,
    ...(parentCode ? { parentCode } : {}),
    labels: { 'uz-Latn': uzLatn, 'uz-Cyrl': uzCyrl, ru, en },
  };
}

/** Districts of one region. Declared after the region so the parent resolves. */
function districts(
  parentCode: string,
  rows: [string, string, string, string, string][],
): SeedItem[] {
  return rows.map(([code, uzLatn, uzCyrl, ru, en]) =>
    place(code, uzLatn, uzCyrl, ru, en, parentCode),
  );
}

