import type { DictionaryCategory } from '@infra/db/database.types';

import type { SeedItem, SeedType } from '../seed-types';

/**
 * Occupations and work types, across all five §2.1 categories.
 *
 * The `category` on each row is the load-bearing part: §5.2 drives the profile and
 * vacancy field sets from it, so a candidate targeting seasonal work is asked about
 * transport and crew readiness while one targeting a professional role is not. An
 * occupation in the wrong category produces a form asking the wrong questions.
 *
 * Compiled to cover the labour market the specification describes, using §2.1's own
 * examples as the anchor for each category. It is a **starting set, not an approved
 * classifier**: the client owns the final list (§13.2), and this is deliberately
 * broad enough to build and demo M3, M5, M6 and the §7.4 search scenario against.
 *
 * Not derived from a formal classifier (ISCO-08, or the national OKPDTR). Mapping to
 * one would be a worthwhile later exercise - it buys statistics and interoperability
 * - but it would also impose classifier granularity on a picker, and "Bank teller"
 * is what a jobseeker searches for.
 */

/** Labels in the order **uz-Latn, uz-Cyrl, ru, en**; see locations.data.ts. */
function job(
  category: DictionaryCategory,
  code: string,
  uzLatn: string,
  uzCyrl: string,
  ru: string,
  en: string,
): SeedItem {
  return {
    code,
    category,
    labels: { 'uz-Latn': uzLatn, 'uz-Cyrl': uzCyrl, ru, en },
  };
}

function group(
  category: DictionaryCategory,
  rows: [string, string, string, string, string][],
): SeedItem[] {
  return rows.map(([code, uzLatn, uzCyrl, ru, en]) =>
    job(category, code, uzLatn, uzCyrl, ru, en),
  );
}

